async function seed() {
  console.log("Seeding 100 viral articles...");
  let count = 0;
  for (let i = 0; i < titles.length; i++) {
    const title = titles[i];
    const category = categories[i % categories.length];
    const imageUrl = categoryImages[category as keyof typeof categoryImages];
    const baseSlug = slugify(title, { lower: true, strict: true, locale: 'hi' }) || `viral-article-${i}`;
    let slug = baseSlug;
    
    // Add randomness to publish date to spread them out over the last 30 days
    const date = new Date();
    date.setDate(date.getDate() - Math.floor(Math.random() * 30));
    date.setHours(Math.floor(Math.random() * 24));

    try {
      await db.insert(articles).values({
        title: title,
        slug: slug + '-' + Date.now().toString().slice(-4),
        content: sampleContent,
        category: category,
        imageUrl: imageUrl,
        seoTitle: title + " - हैरान करने वाले तथ्य",
        seoDescription: title + " के बारे में पूरी जानकारी और अनसुने रहस्य जो आपको जरूर जानने चाहिए।",
        keywords: category + ", viral, trending, india",
        status: "published",
        publishedDate: date,
        views: Math.floor(Math.random() * 5000) + 100
      });
      count++;
    } catch (e) {
      console.error("Error inserting:", title, e);
    }
  }
  console.log(`Successfully seeded ${count} viral articles!`);
  process.exit(0);
}

seed();
